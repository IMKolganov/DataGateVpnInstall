#!/usr/bin/env bash
# Rebuild blocklist/ru-services.domains from the DataGate Monitor DNS log (VpnDnsQueryLogs).
#
# Zones listed in ZONES are blocked with every subdomain. Hosts outside those zones (MAX video on the
# shared okcdn.ru CDN) are taken from what VPN clients actually resolved, so the list follows the apps.
# CIDRs stay hand-curated in blocklist/ru-services.cidrs: a range is listed only when no other service
# shares it. --check-cidrs resolves every domain and prints the addresses the CIDR list does not cover.
#
# Usage:
#   DATABASE_URL=postgres://user:pass@host:5432/db ./scripts/blocklist-from-db.sh [--days 180] [--check-cidrs]
#   PSQL="docker exec -i some-postgres psql -U postgres -d datagate" ./scripts/blocklist-from-db.sh
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
die() { echo "ERROR: $*" >&2; exit 1; }

DAYS=180
CHECK_CIDRS=0
SCHEMA="${DB_SCHEMA:-xgb_dashopnvpn}"
OUT="${BLOCKLIST_DOMAINS_FILE:-$ROOT_DIR/blocklist/ru-services.domains}"
CIDRS="${BLOCKLIST_CIDRS_FILE:-$ROOT_DIR/blocklist/ru-services.cidrs}"

# MAX messenger and Gosuslugi. Each zone covers all of its subdomains in dnsmasq.
ZONES=(oneme.ru max.ru gosuslugi.ru gu-st.ru)
# Hosts on shared zones, matched against the DNS log (PostgreSQL regex).
HOST_PATTERNS=('^maxvd[0-9]+\.okcdn\.ru$')

while [[ $# -gt 0 ]]; do
  case "$1" in
    --days) DAYS="${2:?--days needs a number}"; shift 2 ;;
    --check-cidrs) CHECK_CIDRS=1; shift ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) die "unknown argument: $1" ;;
  esac
done
[[ "$DAYS" =~ ^[0-9]+$ ]] || die "--days must be a number"
[[ "$SCHEMA" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || die "DB_SCHEMA must be a plain identifier"

if [[ -n "${PSQL:-}" ]]; then
  read -r -a psql_cmd <<<"$PSQL"
elif [[ -n "${DATABASE_URL:-}" ]]; then
  command -v psql >/dev/null || die "psql not found; install postgresql-client or set PSQL"
  psql_cmd=(psql "$DATABASE_URL")
else
  die "set DATABASE_URL or PSQL"
fi

pattern_sql=""
for p in "${HOST_PATTERNS[@]}"; do
  pattern_sql+="${pattern_sql:+ OR }d ~ '${p}'"
done

seen_domains() {
  local where="$1"
  "${psql_cmd[@]}" -X -At -v ON_ERROR_STOP=1 -c "SELECT DISTINCT d FROM (
    SELECT lower(rtrim(\"Domain\", '.')) AS d
    FROM \"${SCHEMA}\".\"VpnDnsQueryLogs\"
    WHERE \"QueriedAtUtc\" > now() - interval '${DAYS} days'
  ) q WHERE ${where} ORDER BY 1;"
}

hosts="$(seen_domains "$pattern_sql")" || die "DNS log query failed"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by scripts/blocklist-from-db.sh on $(date -u +%Y-%m-%d) from ${DAYS} days of VpnDnsQueryLogs."
  echo "# One domain per line; each blocks itself and all subdomains. Edit ZONES in the script, not here."
  printf '%s\n' "${ZONES[@]}"
  while IFS= read -r host; do
    [[ -n "$host" && "$host" =~ ^[a-z0-9.-]+$ ]] || continue
    covered=0
    for zone in "${ZONES[@]}"; do
      [[ "$host" == "$zone" || "$host" == *".$zone" ]] && covered=1 && break
    done
    [[ "$covered" -eq 0 ]] && echo "$host"
  done <<<"$hosts"
} >"$tmp"
mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $(grep -cv '^#' "$OUT") domains → $OUT"

if [[ "$CHECK_CIDRS" -eq 1 ]]; then
  command -v dig >/dev/null || die "dig not found (dnsutils)"
  [[ -f "$CIDRS" ]] || die "CIDR list not found: $CIDRS"
  # Resolve zone apexes plus every host seen in the log under those zones.
  zone_sql=""
  for zone in "${ZONES[@]}"; do
    zone_sql+="${zone_sql:+ OR }d = '${zone}' OR d LIKE '%.${zone}'"
  done
  names="$(seen_domains "${pattern_sql} OR ${zone_sql}")" || die "DNS log query failed"
  while IFS= read -r name; do
    [[ -n "$name" ]] || continue
    dig +short +time=2 +tries=1 A "$name" | grep -E '^[0-9.]+$' | sed "s|\$| $name|" || true
  done <<<"$names" | python3 -c '
import ipaddress, sys
nets = [ipaddress.ip_network(l.split("#")[0].strip()) for l in open(sys.argv[1]) if l.split("#")[0].strip()]
missed = {}
for line in sys.stdin:
    ip, name = line.split()
    if not any(ipaddress.ip_address(ip) in n for n in nets):
        missed.setdefault(str(ipaddress.ip_network(ip + "/24", strict=False)), set()).add(name)
for net, names in sorted(missed.items()):
    print(f"not in CIDR list: {net}  ({", ".join(sorted(names)[:4])}{" …" if len(names) > 4 else ""})")
print("CIDR check done: " + ("all resolved addresses covered" if not missed else f"{len(missed)} /24 not covered — DNS block only; add a range only if no other service uses it"))
' "$CIDRS"
fi
